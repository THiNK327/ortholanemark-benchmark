"""Dataset shim that feeds our clean_gt sidecars to the vendored SCNN model.

Mirrors the sample format the upstream `dataset/Tusimple.py:__getitem__`
produces (the format consumed by upstream's `train.py:80-82`), so the
vendored SCNN training loop runs unchanged.

Per-sample dict:
    img       : float32 tensor (3, H, W), ImageNet-normalized BGR (mirrors
                upstream which keeps OpenCV BGR order on the wire).
    segLabel  : int64  tensor (H, W) with values in {0, 1, 2}
                  (0=background, 1=left lane, 2=right lane)
    exist     : float32 tensor (2,)  in {0.0, 1.0}
    img_name  : str (the image path, used only for logging)

Adaptations from upstream's Tusimple dataset:
    - We read 1-channel grayscale pavement images and replicate to 3 channels
      (upstream reads 3-ch RGB from JPEG). This is the standard way to
      feed a 3-channel ImageNet-pretrained backbone with single-channel
      input, and is what the literature does when applying SCNN to
      grayscale inputs (e.g., medical imaging follow-ups).
    - The segmentation target is painted from our polynomial GT at the
      training input resolution. Upstream loads pre-rendered PNG masks
      pre-generated by `dataset/Tusimple.py:preprocess`; we paint on the
      fly because our GT is polynomials, not pixel masks.
    - Line width on the segmentation mask defaults to 8 px (matches
      what the harryhan618 port uses when generating TuSimple masks;
      see their `dataset/Tusimple.py:_gen_label_for_json`).
"""

from __future__ import annotations

import json
from pathlib import Path

import cv2
import numpy as np
import torch
from torch.utils.data import Dataset

from ortholanemark.data.lane_gt import LaneGeometricTruth


# ImageNet normalization (mean / std) — upstream uses these in train.py.
_IMAGENET_MEAN = np.array([0.485, 0.456, 0.406], dtype=np.float32)
_IMAGENET_STD = np.array([0.229, 0.224, 0.225], dtype=np.float32)


def _load_gt_pair(clean_gt_path: str):
    with open(clean_gt_path, 'r', encoding='utf-8') as f:
        d = json.load(f)
    H = int(d['image_size']['height'])
    W = int(d['image_size']['width'])
    gL = LaneGeometricTruth.from_clean_gt_dict(d['left_lane'])
    gR = LaneGeometricTruth.from_clean_gt_dict(d['right_lane'])
    if gL is None:
        gL = LaneGeometricTruth(False, np.zeros(1), 0, None, [])
    if gR is None:
        gR = LaneGeometricTruth(False, np.zeros(1), 0, None, [])
    return gL, gR, H, W


def _paint_lane_mask(gt: LaneGeometricTruth,
                     H_orig: int, W_orig: int,
                     input_h: int, input_w: int,
                     line_width: int = 8) -> np.ndarray:
    """Render the GT polynomial as a binary lane mask at (input_h, input_w).
    Returns a (input_h, input_w) bool mask.
    """
    mask = np.zeros((input_h, input_w), dtype=bool)
    if not gt.has_marking:
        return mask
    ys_in = np.arange(input_h, dtype=np.float64)
    ys_orig = ys_in * (H_orig - 1) / max(input_h - 1, 1)
    xs_orig = gt.eval_x_at(ys_orig, W_orig, clamp_to_frame=False)
    xs_in = xs_orig * (input_w - 1) / max(W_orig - 1, 1)
    half = line_width // 2
    for y_i, x_i in zip(ys_in.astype(np.int64), xs_in):
        if not np.isfinite(x_i):
            continue
        xc = int(round(float(x_i)))
        if xc < 0 or xc >= input_w:
            continue
        x_lo = max(0, xc - half)
        x_hi = min(input_w, xc + half + 1)
        mask[y_i, x_lo:x_hi] = True
    return mask


class SCNNFaithfulDataset(Dataset):
    """Reads our manifest_paper.json split, returns samples in upstream
    SCNN's expected format.

    `rotation_deg > 0` (train only) applies the ±deg random rotation
    that upstream's `transform_train = Compose(Resize(...), Rotation(2),
    ToTensor(), Normalize(...))` does. Both the input image and the
    segmentation mask get the same rotation, mirroring upstream's
    `utils/transforms/data_augmentation.py`.
    """

    def __init__(self,
                 manifest_path: str,
                 split: str,
                 input_h: int = 800,
                 input_w: int = 320,
                 line_width: int = 8,
                 rotation_deg: float = 0.0):
        with open(manifest_path, 'r') as f:
            m = json.load(f)
        self.entries = list(m['splits'].get(split, []))
        self.input_h = int(input_h)
        self.input_w = int(input_w)
        self.line_width = int(line_width)
        self.rotation_deg = float(rotation_deg)

    def __len__(self) -> int:
        return len(self.entries)

    def __getitem__(self, idx: int) -> dict:
        e = self.entries[idx]
        # Load 1-ch grayscale, resize to model input, replicate to 3-ch.
        img = cv2.imread(e['image_path'], cv2.IMREAD_GRAYSCALE)
        if img is None:
            raise FileNotFoundError(e['image_path'])
        H_orig, W_orig = img.shape[:2]
        img_r = cv2.resize(img, (self.input_w, self.input_h),
                           interpolation=cv2.INTER_AREA)

        # Paint seg mask: 0=bg, 1=L, 2=R.
        gL, gR, H_o, W_o = _load_gt_pair(e['clean_gt_path'])
        seg = np.zeros((self.input_h, self.input_w), dtype=np.int64)
        mL = _paint_lane_mask(gL, H_o, W_o, self.input_h, self.input_w,
                              self.line_width)
        mR = _paint_lane_mask(gR, H_o, W_o, self.input_h, self.input_w,
                              self.line_width)
        seg[mL] = 1
        seg[mR] = 2  # if L and R overlap (rare), R wins — matches our
                     # simplified SCNN behaviour and is functionally
                     # equivalent for separation training.

        # Upstream `Rotation(2)` random rotation. Same rotation applied
        # to the image (bilinear) and the seg mask (nearest-neighbour).
        if self.rotation_deg > 0.0:
            ang = float(np.random.uniform(-self.rotation_deg,
                                           self.rotation_deg))
            center = (self.input_w / 2.0, self.input_h / 2.0)
            M = cv2.getRotationMatrix2D(center, ang, 1.0)
            img_r = cv2.warpAffine(img_r, M, (self.input_w, self.input_h),
                                    flags=cv2.INTER_LINEAR,
                                    borderMode=cv2.BORDER_REFLECT)
            seg = cv2.warpAffine(seg.astype(np.uint8), M,
                                  (self.input_w, self.input_h),
                                  flags=cv2.INTER_NEAREST,
                                  borderMode=cv2.BORDER_CONSTANT,
                                  borderValue=0).astype(np.int64)

        # Replicate grayscale into 3 channels. We feed in BGR order to
        # match upstream's cv2.imread default, but since all 3 channels
        # are identical the order is moot here.
        img_3 = np.stack([img_r, img_r, img_r], axis=-1).astype(np.float32) / 255.0
        img_3 = (img_3 - _IMAGENET_MEAN) / _IMAGENET_STD
        img_t = torch.from_numpy(
            np.ascontiguousarray(img_3.transpose(2, 0, 1))).float()
        seg_t = torch.from_numpy(seg).long()

        exist_t = torch.tensor([float(gL.has_marking),
                                float(gR.has_marking)], dtype=torch.float32)

        return {
            'img': img_t,
            'segLabel': seg_t,
            'exist': exist_t,
            'img_name': e['image_path'],
            'stem': e.get('stem', ''),
            'project': e.get('project', 'unknown'),
            'image_h_orig': H_orig,
            'image_w_orig': W_orig,
        }


def collate(batch: list) -> dict:
    """Stack tensors, keep metadata as lists."""
    out = {}
    keys = batch[0].keys()
    for k in keys:
        if isinstance(batch[0][k], torch.Tensor):
            out[k] = torch.stack([b[k] for b in batch], dim=0)
        else:
            out[k] = [b[k] for b in batch]
    return out
